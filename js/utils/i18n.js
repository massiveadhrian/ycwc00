let currentLanguage = 'English';

/**
 * Set the current language.
 */
export function setLanguage(lang) {
  if (translations[lang]) {
    currentLanguage = lang;
    try {
      localStorage.setItem('dhryzn_lang', lang);
    } catch (e) {}
  }
}

/**
 * Get the current language, synchronized with Store settings & localStorage.
 */
export function getLanguage() {
  if (typeof window !== 'undefined' && window.__dhryzn_store__) {
    const settings = window.__dhryzn_store__.get('settings');
    if (settings && settings.language && translations[settings.language]) {
      currentLanguage = settings.language;
      return currentLanguage;
    }
  }
  if (typeof localStorage !== 'undefined') {
    try {
      const savedLang = localStorage.getItem('dhryzn_lang');
      if (savedLang && translations[savedLang]) {
        currentLanguage = savedLang;
        return currentLanguage;
      }
      const stateRaw = localStorage.getItem('dhryzn_state');
      if (stateRaw) {
        const parsed = JSON.parse(stateRaw);
        if (parsed?.settings?.language && translations[parsed.settings.language]) {
          currentLanguage = parsed.settings.language;
          return currentLanguage;
        }
      }
    } catch (e) {}
  }
  return currentLanguage;
}

/**
 * Get translated string for the given key.
 * Falls back to English, then to the key itself.
 */
export function t(key) {
  const activeLang = getLanguage();
  const lang = translations[activeLang];
  if (lang && lang[key] !== undefined) return lang[key];
  // Fallback to English
  const en = translations['English'];
  if (en && en[key] !== undefined) return en[key];
  return key;
}
